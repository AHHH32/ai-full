def sentences(text: str) -> list[str]:
    return [part.strip() for part in re.findall(r"[^。！？!?]+[。！？!?]?", text) if part.strip()]


def audio_key(text: str) -> str:
    import hashlib

    clean = re.sub(r"\s+", "", text).rstrip("。！？!?")
    return hashlib.sha256(clean.encode()).hexdigest()[:16]


def intent(text: str) -> str:
    for words, answer in (
        (("照片", "相片", "看看", "海边"), "photo"),
        (("消息", "短信", "联系", "打电话"), "message"),
        (("陪", "一起等", "坐一会"), "company"),
        (("等谁", "等人", "朋友", "为什么", "还没走"), "waiting"),
        (("咖啡", "喝", "好喝"), "coffee"),
        (("你好", "名字", "认识"), "hello"),
    ):
        if any(word in text for word in words):
            return answer
    return "chat"


